    public static void ApplyLanguage(string? langCode)
    {
        string code = string.IsNullOrWhiteSpace(langCode) || !Dictionaries.ContainsKey(langCode)
            ? "uk"
            : langCode.ToLowerInvariant();

        CurrentLanguageCode = code;
        var dict = Dictionaries[code];
        var fallback = Dictionaries["uk"];

        var appResources = Application.Current?.Resources;
        if (appResources != null)
        {
            foreach (var kv in fallback)
            {
                appResources[kv.Key] = dict.TryGetValue(kv.Key, out var translated) ? translated : kv.Value;
            }

            foreach (var (src, alias) in KeyAliases)
            {
                if (appResources[src] is string val)
                {
                    appResources[alias] = val;
                }
            }

            var wizDict = WizardDictionaries.TryGetValue(code, out var wd) ? wd : WizardDictionaries["uk"];
            var wizFallback = WizardDictionaries["uk"];
            foreach (var kv in wizFallback)
            {
                appResources[kv.Key] = wizDict.TryGetValue(kv.Key, out var translated) ? translated : kv.Value;
            }
        }

        LanguageChanged?.Invoke(code);
    }

    public static string GetString(string key)
    {
        if (Dictionaries.TryGetValue(CurrentLanguageCode, out var dict) && dict.TryGetValue(key, out var val))
            return val;
        if (WizardDictionaries.TryGetValue(CurrentLanguageCode, out var wdict) && wdict.TryGetValue(key, out var wval))
            return wval;
        if (Dictionaries["uk"].TryGetValue(key, out var fb))
            return fb;
        if (WizardDictionaries["uk"].TryGetValue(key, out var wfb))
            return wfb;
        return key;
    }
